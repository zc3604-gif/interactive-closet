function setup() {
  createCanvas(windowWidth, windowHeight);
  textFont("monospace");
  noLoop();
}

function draw() {
  background(255);
  fill(0);
  noStroke();
  textAlign(LEFT, TOP);

  const lines = art.split("\n");
  const columns = Math.max(...lines.map(line => line.length));
  const padding = 20;

  // Fit the artwork inside the canvas.
  textSize(20);
  const cellRatio = textWidth("M") / 20;
  const fontSize = Math.min(
    (width - padding * 2) / (columns * cellRatio),
    (height - padding * 2) / (lines.length * 1.15)
  );

  textSize(fontSize);
  const lineHeight = fontSize * 1.15;
  const x = (width - columns * textWidth("M")) / 2;
  const y = (height - lines.length * lineHeight) / 2;

  lines.forEach((line, i) => text(line, x, y + i * lineHeight));
}

function windowResized() {
  resizeCanvas(windowWidth, windowHeight);
  redraw();
}